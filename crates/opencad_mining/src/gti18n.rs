pub fn g() -> &'static GtStrings {
    for_lang(lang())
}

pub fn for_lang(l: Lang) -> &'static GtStrings {
    match l {
        Lang::Es => &ES,
        Lang::En => &EN,
        Lang::Pt => &PT,
    }
}

impl GtStrings {
    /// Display name of a column.
    pub fn field(&self, f: GtField) -> String {
        use GtField::*;
        let i = match f {
            Hole => 0,
            From => 1,
            To => 2,
            Axis => 3,
            Chainage => 4,
            Lith => 5,
            Ff => 6,
            Spacing => 7,
            Persistence => 8,
            Aperture => 9,
            Roughness => 10,
            Infilling => 11,
            Weathering => 12,
            Water => 13,
            RCondition => 14,
            Density => 15,
            Dip => 16,
            DipDir => 17,
            RStrength => return "rating UCS".into(),
            Rqd => return "RQD".into(),
            Ucs => return "UCS".into(),
            Is50 => return "Is50".into(),
            RRqd => return "rating RQD".into(),
            RSpacing => return format!("rating {}", self.fields[7]),
            RWater => return format!("rating {}", self.fields[13]),
            Rmr => return "RMR".into(),
            Jn => return "Jn".into(),
            Jr => return "Jr".into(),
            Ja => return "Ja".into(),
            Jw => return "Jw".into(),
            Srf => return "SRF".into(),
            Q => return "Q".into(),
            Gsi => return "GSI".into(),
            Mi => return "mi".into(),
            Ei => return "Ei".into(),
            Poisson => return "ν".into(),
            X => return "X".into(),
            Y => return "Y".into(),
            Z => return "Z".into(),
        };
        self.fields[i].to_string()
    }

    pub fn derived(&self, d: Derived) -> &'static str {
        use Derived::*;
        self.derived[match d {
            UcsFromLab => 0,
            Is50FromLab => 1,
            RqdFromFf => 2,
            SpacingFromFf => 3,
            RmrGiven => 4,
            QGiven => 5,
            GsiGiven => 6,
            RmrFromQ => 7,
            QFromRmr => 8,
            GsiFromRmr => 9,
            GsiFromQ => 10,
        }]
    }

    pub fn locate_error(&self, e: &LocateError) -> String {
        match e {
            LocateError::UnknownHole(h) => fmt(self.e_unknown_hole, &[h]),
            LocateError::NoDepth => self.e_no_depth.into(),
            LocateError::NoCoordinates => self.e_no_coords.into(),
            LocateError::UnknownAxis(a) => fmt(self.e_unknown_axis, &[a]),
            LocateError::NoAxis => self.e_no_axis.into(),
            LocateError::AxisTooShort => self.e_axis_short.into(),
        }
    }
}

