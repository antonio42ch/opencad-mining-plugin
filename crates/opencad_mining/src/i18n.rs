//! UI strings in Spanish, English and Portuguese. Every language is a full
//! `Strings` value, so a missing translation is a compile error.
//!
//! Language: `OPENMINING_LANG`, else `LC_ALL` / `LC_MESSAGES` / `LANG`
//! (`es*`, `pt*`, anything else -> English).

use std::sync::OnceLock;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Lang {
    Es,
    En,
    Pt,
}

pub fn detect() -> Lang {
    let v = ["OPENMINING_LANG", "LC_ALL", "LC_MESSAGES", "LANG"]
        .iter()
        .find_map(|k| std::env::var(k).ok().filter(|v| !v.is_empty()))
        .unwrap_or_default()
        .to_lowercase();
    if v.starts_with("es") {
        Lang::Es
    } else if v.starts_with("pt") {
        Lang::Pt
    } else {
        Lang::En
    }
}

pub fn lang() -> Lang {
    static L: OnceLock<Lang> = OnceLock::new();
    *L.get_or_init(detect)
}

pub fn s() -> &'static Strings {
    for_lang(lang())
}

pub fn for_lang(l: Lang) -> &'static Strings {
    match l {
        Lang::Es => &ES,
        Lang::En => &EN,
        Lang::Pt => &PT,
    }
}

