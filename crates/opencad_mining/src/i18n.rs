impl Strings {
    pub fn field(&self, key: &str) -> &'static str {
        self.field_names.iter().find(|(k, _)| *k == key).map_or("?", |(_, v)| v)
    }

    pub fn table(&self, t: drillhole_engine::error::TableKind) -> &'static str {
        use drillhole_engine::error::TableKind::*;
        self.table_names[match t {
            Collar => 0,
            Survey => 1,
            Assay => 2,
            Geo => 3,
        }]
    }

    pub fn import_error(&self, e: &drillhole_engine::ImportError) -> String {
        use drillhole_engine::ImportError::*;
        let t = self.table(e.table());
        match e {
            Empty { .. } => fmt(self.e_empty, &[&t]),
            MissingIdColumn { .. } => fmt(self.e_missing_id, &[&t]),
            MissingColumn { field, .. } => fmt(self.e_missing_col, &[&t, &self.field(field)]),
            UnknownMappedColumn { field, column, .. } => fmt(self.e_unknown_mapped, &[&t, &self.field(field), column]),
            Io { message, .. } | Spreadsheet { message, .. } => fmt(self.e_io, &[&t, message]),
        }
    }
}

