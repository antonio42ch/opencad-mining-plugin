#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn placeholders_match_across_languages() {
        let count = |s: &str| (0..10).filter(|i| s.contains(&format!("{{{i}}}"))).count();
        let pairs = [
            (ES.m_composited, EN.m_composited, PT.m_composited),
            (ES.m_stats, EN.m_stats, PT.m_stats),
            (ES.m_cv_done, EN.m_cv_done, PT.m_cv_done),
            (ES.m_bm_domain, EN.m_bm_domain, PT.m_bm_domain),
            (ES.m_resource_row, EN.m_resource_row, PT.m_resource_row),
            (ES.m_validate_row, EN.m_validate_row, PT.m_validate_row),
            (ES.m_contact_done, EN.m_contact_done, PT.m_contact_done),
        ];
        for (a, b, c) in pairs {
            assert_eq!(count(a), count(b), "{a} / {b}");
            assert_eq!(count(a), count(c), "{a} / {c}");
        }
    }
}
