pub fn r() -> &'static RsStrings {
    for_lang(lang())
}

pub fn for_lang(l: Lang) -> &'static RsStrings {
    match l {
        Lang::Es => &ES,
        Lang::En => &EN,
        Lang::Pt => &PT,
    }
}

